import { test, expect } from "@playwright/test";
import { workingDaysInMonth } from "../../src/lib/working-days";

test.use({ storageState: "tests/e2e/.auth/admin.json" });

// A far-future, arbitrary period no attendance/leave data could possibly
// exist for yet — makes the LOP assertion deterministic: with zero
// check-ins and zero approved leave, every working weekday in the period
// MUST count as Loss of Pay. Real regression protection for the actual
// formula (src/lib/payroll.ts computeLopDays/calculatePayroll), not just
// "the field exists."
const LOP_TEST_MONTH = 1;
const LOP_TEST_YEAR = 2094;

test("payroll generation computes Loss of Pay from real attendance/leave data", async ({ request }) => {
  const employeesRes = await request.get("/api/admin/employees");
  expect(employeesRes.ok()).toBeTruthy();
  const { employees } = await employeesRes.json();
  const rahul = employees.find((e: { full_name: string }) => e.full_name === "Rahul Rater");
  expect(rahul, "seeded staff member 'Rahul Rater' not found").toBeTruthy();

  const generateRes = await request.post("/api/payroll/generate", { data: { month: LOP_TEST_MONTH, year: LOP_TEST_YEAR } });
  expect(generateRes.ok(), `generate failed: ${await generateRes.text()}`).toBeTruthy();
  // generated may be 0 on a re-run (idempotent — already generated by a
  // previous run of this same test) or >0 on a first run; both are fine,
  // the payslip row itself is what we actually check below.
  await generateRes.json();

  const payslipsRes = await request.get(`/api/payroll/payslips?staffId=${rahul.id}`);
  expect(payslipsRes.ok()).toBeTruthy();
  const { payslips } = await payslipsRes.json();
  const payslip = payslips.find((p: { month: number; year: number }) => p.month === LOP_TEST_MONTH && p.year === LOP_TEST_YEAR);
  expect(payslip, "no payslip found for the zero-attendance test period").toBeTruthy();

  // No holidays are declared for this far-future test period, so the
  // expected LOP is simply every working day in it.
  const expectedLopDays = workingDaysInMonth(LOP_TEST_MONTH, LOP_TEST_YEAR, new Set());
  expect(Number(payslip.lop_days)).toBe(expectedLopDays);
  expect(Number(payslip.lop_deduction)).toBeGreaterThan(0);

  // Verify the actual arithmetic end-to-end, not just that the fields
  // are populated: net = gross - pf - esi - pt - tds - lop.
  const expectedNet =
    Number(payslip.gross_salary) -
    Number(payslip.pf_deduction) -
    Number(payslip.esi_deduction) -
    Number(payslip.professional_tax) -
    Number(payslip.tds) -
    Number(payslip.lop_deduction);
  expect(Number(payslip.net_salary)).toBe(expectedNet);
});

test("Payroll page UI: Generate Salary button creates payslips visible in the list", async ({ page }) => {
  await page.goto("/dashboard/admin/payroll");
  await expect(page.getByRole("heading", { name: "Payroll" })).toBeVisible();

  // A period unlikely to collide with the API-level test above or any
  // other run — this one exercises the actual button click + result
  // rendering, not the calculation itself. Scoped to the "Generate
  // Salary" panel specifically — the page has another <select>/number
  // input earlier (the salary-structure form) that would otherwise match first.
  const generatePanel = page.locator("text=Generate Salary").locator("xpath=ancestor::div[contains(@class,'rounded-2xl')][1]");
  await generatePanel.locator("select").selectOption("2");
  await generatePanel.locator('input[type="number"]').fill("2095");

  await generatePanel.getByRole("button", { name: /Generate Salary/ }).click();
  await expect(page.getByText(/Generated \d+ payslip|No new payslips/)).toBeVisible({ timeout: 15000 });
});
